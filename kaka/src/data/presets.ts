export function createSvgAvatar(label: string, bgColor: string): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100" viewBox="0 0 100 100">
    <rect width="100" height="100" fill="${bgColor}" rx="20"/>
    <text x="50" y="62" font-family="Montserrat, sans-serif" font-size="48" font-weight="900" fill="#ffffff" text-anchor="middle">${label}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

